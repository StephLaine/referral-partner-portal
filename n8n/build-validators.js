#!/usr/bin/env node
// Regenerates the four validator Code nodes inside referral-partner-program.json
// from one template, so they can't drift apart. Run after editing a schema:
//   node n8n/build-validators.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const FILE = path.join(__dirname, 'referral-partner-program.json');

const VALIDATORS = {
  'Validate Lead Qualification': {
    original: 'Prepare Lead Data1', flag: 'validate_lead_qualification',
    required: ['lead_score'],
    schema: { lead_score: ['hot', 'warm', 'cold'], confidence: 'unit', reasoning: 'string' },
    fallback: "{ lead_score: 'warm', confidence: 0, reasoning: 'fallback - agent output invalid' }"
  },
  'Validate CRM Enrichment': {
    original: 'Prepare Lead Data1', flag: 'validate_crm_enrichment',
    required: ['lifecyclestage'],
    schema: { lifecyclestage: ['lead', 'opportunity'], recommended_product: 'string', internal_note: 'string' },
    fallback: "{ lifecyclestage: 'lead', recommended_product: 'General inquiry', internal_note: 'fallback - agent output invalid' }"
  },
  'Validate Partner Communication': {
    original: 'Prepare Lead Data1', flag: 'validate_partner_communication',
    required: ['partner_email_body', 'prospect_email_body'],
    schema: { partner_email_body: 'string', prospect_email_body: 'string' },
    fallback: "{ partner_email_body: 'Thank you for sending us a referral for ' + original.prospect_name + '. We have received the referral and our team will follow up with the prospect.', prospect_email_body: \"Thank you for your interest. We've received your request and a member of our team will follow up with you shortly.\" }"
  },
  'Validate Referral Decision': {
    original: 'Merge ABC', flag: 'validate_referral_decision',
    required: ['routing_tier'],
    schema: { routing_tier: ['immediate', 'standard', 'nurture'], final_summary: 'string' },
    fallback: "{ routing_tier: 'standard', final_summary: 'Automated summary unavailable - agent output invalid; please review referral manually.' }"
  }
};

function code(v) {
  return `// Generated by n8n/build-validators.js. Edit the schema there, not here.
const original = $('${v.original}').item.json;
const REQUIRED = ${JSON.stringify(v.required)};
const SCHEMA = ${JSON.stringify(v.schema)};
let parsed;
let valid = true;
let errorMsg = '';
try {
  const block = ($json.content || []).find((c) => c && c.type === 'text');
  const raw = String(block ? block.text : '').trim().replace(/^\`\`\`(?:json)?\\s*/i, '').replace(/\\s*\`\`\`$/, '');
  const data = JSON.parse(raw);
  if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('answer is not a JSON object');
  for (const key of REQUIRED) if (!(key in data)) throw new Error('missing required key: ' + key);
  // Keep only the keys this agent is allowed to set, so a model answer can
  // never overwrite lead fields such as prospect_email.
  parsed = {};
  for (const [key, rule] of Object.entries(SCHEMA)) {
    if (!(key in data)) continue;
    const value = data[key];
    const ok = Array.isArray(rule) ? rule.includes(value)
      : rule === 'unit' ? typeof value === 'number' && value >= 0 && value <= 1
      : typeof value === 'string';
    if (!ok) throw new Error('invalid ' + key + ': ' + JSON.stringify(value));
    parsed[key] = value;
  }
} catch (e) {
  valid = false;
  errorMsg = e.message;
  parsed = ${v.fallback};
}
return [{ json: { ...original, ...parsed, ['${v.flag}_valid']: valid, ['${v.flag}_error']: errorMsg } }];`;
}

const wf = JSON.parse(fs.readFileSync(FILE, 'utf8'));
for (const [name, v] of Object.entries(VALIDATORS)) {
  const node = wf.nodes.find(n => n.name === name);
  if (!node) throw new Error('missing node ' + name);
  node.parameters.jsCode = code(v);
}
fs.writeFileSync(FILE, JSON.stringify(wf, null, 2) + '\n');
console.log('Regenerated', Object.keys(VALIDATORS).length, 'validators in', path.relative(process.cwd(), FILE));
